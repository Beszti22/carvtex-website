  function applyLang(lang){
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var key = el.getAttribute('data-i18n');
      var dict = translations[lang];
      if(dict && dict[key] !== undefined){ el.innerHTML = dict[key]; }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
      var key = el.getAttribute('data-i18n-placeholder');
      var dict = translations[lang];
      if(dict && dict[key] !== undefined){ el.setAttribute('placeholder', dict[key]); }
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function(el){
      var key = el.getAttribute('data-i18n-aria');
      var dict = translations[lang];
      if(dict && dict[key] !== undefined){ el.setAttribute('aria-label', dict[key]); }
    });
    document.documentElement.lang = lang;
    var btnHu = document.getElementById('btnHu');
    var btnEn = document.getElementById('btnEn');
    if(btnHu) btnHu.setAttribute('aria-pressed', lang === 'hu' ? 'true' : 'false');
    if(btnEn) btnEn.setAttribute('aria-pressed', lang === 'en' ? 'true' : 'false');
    try {
      window.dispatchEvent(new CustomEvent('carvtex:langchange', { detail: { lang: lang } }));
    } catch (e) {}
  }

  var STORAGE_KEY = 'carvtex-lang';

  function getSavedLang(){
    try{
      return localStorage.getItem(STORAGE_KEY);
    }catch(e){
      return null;
    }
  }

  function saveLang(lang){
    try{
      localStorage.setItem(STORAGE_KEY, lang);
    }catch(e){
      /* localStorage unavailable (private mode etc.) - language just won't persist */
    }
  }

